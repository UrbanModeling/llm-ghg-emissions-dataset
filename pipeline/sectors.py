def _from_text(texts, rules) -> str:
    for t in texts:
        low = str(t).lower()
        if low.strip():
            for group, pat in rules:
                if re.search(pat, low):
                    return group
    return ""


def sector_group(words: str, *more: str) -> str:
    w = str(words).strip().lower()
    if w in SECTOR_MAP_LOW:
        return SECTOR_MAP_LOW[w]
    if w not in NO_SECTOR and MULTI_RE.search(w):
        return "Multi-sector"
    texts = [w, *more] if w not in NO_SECTOR else list(more)
    return _from_text(texts, SECTOR_RULES) or _from_text(texts, EXTRA_SECTOR_RULES)
